#!/usr/bin/env python3
"""Generates the handler libraries and notification handlers for the mediator benchmarks.

MediatR50 holds Request{i}(int Value) : MediatR.IRequest<int> and Request{i}Handler (returns Value + i) for i < 50.
Mediator50 holds the same records and handlers on Mediator.Abstractions, plus MediatorS50.Add, which calls the
AddMediator that Mediator.SourceGenerator generates for that library alone (types generated as internal), so each
library's startup covers exactly its 50 handlers and nothing from the benchmark project.
NotificationHandlers.g.cs (benchmark project) holds one handler for Notification1 and five for Notification5 per library;
each one increments Probe.NotificationCalls and completes synchronously.
Run from anywhere: python3 benchmarks/CSharpEssentials.Mediator.Benchmarks/generate-handlers.py
"""
from pathlib import Path

N = 50
FANOUT = 5
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / "CSharpEssentials.Mediator.Benchmarks.Handlers"
PREFIX = "CSharpEssentials.Mediator.Benchmarks.Handlers"
ALL_TFMS = "net8.0;net9.0;net10.0;net11.0"
NOWARN = "$(NoWarn);CA1822;CA1050;CA1812;S101;S3903;S1118;CA1515;S2068;IDE0008;IDE0021;IDE0005;IDE0078"
TASKS = "global::System.Threading.Tasks"
CT = "global::System.Threading.CancellationToken"
DI = "global::Microsoft.Extensions.DependencyInjection"

HEADER = """// <auto-generated/>
// Generated by benchmarks/CSharpEssentials.Mediator.Benchmarks/generate-handlers.py. Do not edit.
#nullable enable
"""


def csproj(packages: str) -> str:
    return (f"""<!-- <auto-generated/> Generated by benchmarks/CSharpEssentials.Mediator.Benchmarks/generate-handlers.py. Do not edit. -->
<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <TargetFrameworks>{ALL_TFMS}</TargetFrameworks>
    <IsPackable>false</IsPackable>
    <NoWarn>{NOWARN}</NoWarn>
  </PropertyGroup>

  <ItemGroup>
{packages}
  </ItemGroup>

</Project>
""")


def mediatr() -> str:
    body = []
    for i in range(N):
        body.append(f"public sealed record Request{i}(int Value) : global::MediatR.IRequest<int>;\n")
        body.append(f"public sealed class Request{i}Handler : global::MediatR.IRequestHandler<Request{i}, int>\n{{\n"
                    f"    public {TASKS}.Task<int> Handle(Request{i} request, {CT} cancellationToken) => "
                    f"{TASKS}.Task.FromResult(request.Value + {i});\n}}\n")
    return HEADER + f"\nnamespace {PREFIX}.MediatR50;\n\n" + "\n".join(body)


def mediator() -> str:
    body = []
    for i in range(N):
        body.append(f"public sealed record Request{i}(int Value) : global::Mediator.IRequest<int>;\n")
        body.append(f"public sealed class Request{i}Handler : global::Mediator.IRequestHandler<Request{i}, int>\n{{\n"
                    f"    public {TASKS}.ValueTask<int> Handle(Request{i} request, {CT} cancellationToken) => "
                    f"new(request.Value + {i});\n}}\n")
    body.append("// https://github.com/martinothamar/Mediator/blob/v3.0.2/README.md#34-configuration\n"
                "public static class MediatorS50\n{\n"
                f"    public static {DI}.IServiceCollection Add({DI}.IServiceCollection services) =>\n"
                "        services.AddMediator(static options => options.GenerateTypesAsInternal = true);\n}\n")
    return HEADER + "\nusing Microsoft.Extensions.DependencyInjection;\n" + f"\nnamespace {PREFIX}.Mediator50;\n\n" + "\n".join(body)


def notification_handlers() -> str:
    body = []
    handlers = [("Notification1", "Notification1Handler")] + [("Notification5", f"Notification5Handler{k}") for k in range(FANOUT)]
    for notification, name in handlers:
        body.append(f"public sealed class MediatR{name} : global::MediatR.INotificationHandler<{notification}>\n{{\n"
                    f"    public {TASKS}.Task Handle({notification} notification, {CT} cancellationToken)\n    {{\n"
                    f"        Probe.NotificationCalls++;\n        return {TASKS}.Task.CompletedTask;\n    }}\n}}\n")
        body.append(f"public sealed class Mediator{name} : global::Mediator.INotificationHandler<{notification}>\n{{\n"
                    f"    public {TASKS}.ValueTask Handle({notification} notification, {CT} cancellationToken)\n    {{\n"
                    f"        Probe.NotificationCalls++;\n        return default;\n    }}\n}}\n")
    return HEADER + "\nnamespace CSharpEssentials.Mediator.Benchmarks;\n\n" + "\n".join(body)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


write(ROOT / "MediatR50" / f"{PREFIX}.MediatR50.csproj",
      csproj('    <PackageReference Include="MediatR" />'))
write(ROOT / "MediatR50" / "Handlers.g.cs", mediatr())
write(ROOT / "Mediator50" / f"{PREFIX}.Mediator50.csproj",
      csproj('    <PackageReference Include="Mediator.Abstractions" VersionOverride="3.0.2" />\n'
             '    <PackageReference Include="Mediator.SourceGenerator" PrivateAssets="all" '
             'IncludeAssets="runtime; build; native; contentfiles; analyzers" />'))
write(ROOT / "Mediator50" / "Handlers.g.cs", mediator())
write(HERE / "NotificationHandlers.g.cs", notification_handlers())
