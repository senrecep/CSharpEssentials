#!/usr/bin/env bash
# Native AOT report for the enum samples in this folder.
# For each sample: Native AOT publish (IL warnings, success, binary size), then run the native binary: it enumerates the
# 20 members of its Status enum, formats each as its member name, parses the name back case-sensitively (CSE: TryParseWire,
# which ignores case) and exits 0 only when all 20 round-trip and the checksum (values + name lengths) is 971. Wall time is
# the median of RUNS runs after one discarded warm-up run that also records the exit code and output.
# Usage: run-enums-aot.sh [Variant ...]   (default: all; a subset rewrites the report with only those rows).  Env: RUNS (default 5).
# Output: benchmarks/results/enums/aot/aot-report.md, raw logs in .../aot/logs/ (git-ignored by the repo's [Ll]ogs/ rule).
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
OUT="$HERE/../results/enums/aot"
LOGS="$OUT/logs"
RUNS=${RUNS:-5}
ALL=(BclAot CseAot EnumsNetAot NetEscapadesAot)
VARIANTS=("$@")
((${#VARIANTS[@]})) || VARIANTS=("${ALL[@]}")

mkdir -p "$LOGS"
ulimit -c 0 # crashing samples are expected; no core dumps
LOAD0=$(cut -d" " -f1-3 /proc/loadavg)
OUT=$(cd "$OUT" && pwd)
WORK=$(mktemp -d)

cleanup() {
    for v in "${VARIANTS[@]}"; do rm -rf "${HERE:?}/$v/bin" "${HERE:?}/$v/obj"; done
    rm -rf "$WORK"
}
trap cleanup EXIT

median() { printf '%s\n' "$@" | sort -n | awk '{a[NR]=$1} END {print (NR % 2) ? a[(NR + 1) / 2] : int((a[NR / 2] + a[NR / 2 + 1]) / 2)}'; }

# time_run BINARY LOGFILE: sets RC (exit code) and MS (wall ms, rounded).
time_run() {
    local t0 t1
    t0=${EPOCHREALTIME/[.,]/}
    RC=0
    "$1" >"$2" 2>&1 || RC=$?
    t1=${EPOCHREALTIME/[.,]/}
    MS=$(((t1 - t0 + 500) / 1000))
}

clean_obj() { rm -rf "$HERE/$1/bin" "$HERE/$1/obj"; }

ROWS=()
DETAILS=()

for v in "${VARIANTS[@]}"; do
    echo "== $v" >&2
    proj="$HERE/$v/$v.csproj"
    alog="$LOGS/$v.aot-publish.log"

    # Clean first: an incremental publish skips CoreCompile and drops the analyzer warnings.
    # TrimmerSingleWarn=false lists member-level ILC warnings instead of one IL2104/IL3053 line per package assembly.
    # PublishAot comes from the csproj: as a global -p it would also reach the netstandard2.0 CSE generator project
    # reference and fail it with NETSDK1207.
    clean_obj "$v"
    aot_ok=yes
    dotnet publish "$proj" -c Release -r linux-x64 -p:TreatWarningsAsErrors=false \
        -p:TrimmerSingleWarn=false -o "$WORK/$v/aot" --tl:off -clp:NoSummary >"$alog" 2>&1 || aot_ok=no
    grep -E 'warning IL[0-9]+' "$alog" | sed -E 's/ \[[^]]*\]$//; s#^ *##; s#'"${HERE%/benchmarks/*}"'/##' | sort -u >"$WORK/$v.warn" || true
    n_total=$(wc -l <"$WORK/$v.warn")
    n_an=$(grep -cE '\([0-9]+,[0-9]+\): warning IL' "$WORK/$v.warn" || true)
    n_ilc=$((n_total - n_an))
    codes=$(grep -oE 'warning IL[0-9]+' "$WORK/$v.warn" | sed 's/warning //' | sort | uniq -c | awk '{printf "%s%s x%s", (NR > 1 ? ", " : ""), $2, $1}' || true)
    bin="$WORK/$v/aot/$v"
    size="-"
    if [[ $aot_ok == yes && -f $bin ]]; then
        size=$(awk -v b="$(stat -c %s "$bin")" 'BEGIN {printf "%.1f MB", b / 1048576}')
    else
        aot_ok=no
    fi
    clean_obj "$v"

    rc="-"; check="-"; ms="publish failed"
    if [[ $aot_ok == yes ]]; then
        time_run "$bin" "$LOGS/$v.run.log"
        rc=$RC
        check=$(head -c 300 "$LOGS/$v.run.log" | tr '\n' ' ' | sed 's/|/\\|/g; s/ *$//')
        if ((RC == 0)); then
            times=()
            for ((i = 1; i <= RUNS; i++)); do
                time_run "$bin" "$WORK/run.log"
                if ((RC != 0)); then cp "$WORK/run.log" "$LOGS/$v.run.log"; times=(); ms="run $i exited $RC"; break; fi
                times+=("$MS")
            done
            if ((${#times[@]})); then
                ms=$(median "${times[@]}")
                echo "  runs (ms): ${times[*]}" >&2
            fi
        else
            ms="exited $RC"
            size="$size [1]"
        fi
    fi
    ROWS+=("| $v | $aot_ok | $n_total ($n_an analyzer / $n_ilc ILC) | ${codes:--} | $size | $rc | ${check:--} | $ms |")
    detail="### $v"$'\n\n'
    if ((n_total == 0)); then
        detail+="No IL warnings."$'\n'
    else
        detail+='```text'$'\n'"$(cut -c1-400 "$WORK/$v.warn")"$'\n''```'$'\n'
    fi
    DETAILS+=("$detail")
    rm -rf "${WORK:?}/$v"
done

{
    echo "# Enums Native AOT report"
    echo
    echo "Generated by \`benchmarks/enums-aot/run-enums-aot.sh\` on $(date -u +%Y-%m-%dT%H:%MZ)."
    echo "SDK $(dotnet --version), target net10.0, linux-x64, kernel $(uname -r), $(nproc) logical CPUs, load average at start: $LOAD0."
    echo
    echo "- **Packages**: Enums.NET 5.0.0 (its net7.0 build, no dependencies); NetEscapades.EnumGenerators 1.0.0-beta21, the latest prerelease (no stable version has ever shipped); CSharpEssentials.Enums from this repo (net10.0 build) with its generator as an analyzer project reference; BclAot uses only System.Enum."
    echo "- **Input**: every sample declares the same 20-member \`Status\` enum (non-contiguous values) with only the attribute its library needs (CSE \`[StringEnum]\`, NetEscapades \`[EnumExtensions]\`, none for BCL and Enums.NET)."
    echo "- **AOT publish**: \`dotnet publish -c Release -r linux-x64 -p:TreatWarningsAsErrors=false -p:TrimmerSingleWarn=false\` from a clean obj; every sample sets \`PublishAot=true\` in its csproj (as a global \`-p\` it would also reach the CSE generator project reference and fail it with NETSDK1207)."
    echo "  TreatWarningsAsErrors=false is passed on the command line only; nothing is suppressed in the projects."
    echo "  TrimmerSingleWarn=false makes ILC list each warning with its member instead of one IL2104/IL3053 line per package assembly, so counts are higher than a default publish shows."
    echo "- **IL warnings**: distinct \`warning IL\` lines. *analyzer* = Roslyn trim/AOT analyzers at compile time (call sites in the sample); *ILC* = whole-program trim/AOT analysis during native compilation (inside libraries)."
    echo "- **Run**: the native binary enumerates all values, formats each as its member name, parses it back and prints \`parsed 20 checksum 971 ok\`; it exits 0 only when all 20 round-trip. CSE formats with \`ToOptimizedString\` and parses with \`TryParseWire\` (ignores case); Enums.NET uses \`AsString\`/\`Enums.TryParse\`/\`Enums.GetValues\`; NetEscapades \`ToStringFast\`/\`TryParse\`/\`GetValues\`; BCL \`ToString\`/\`Enum.TryParse\`/\`Enum.GetValues<T>\`."
    echo "- **Wall time**: ms from process start to exit, median of $RUNS runs after one discarded warm-up run. Machine-noise sensitive; regenerate on a quiet machine before quoting it."
    echo
    echo "| Variant | AOT publish | IL warnings (distinct) | Warning codes | Native binary | Exit code | Output (warm-up run) | Wall time (ms) |"
    echo "|---|---|---|---|---|---|---|---|"
    printf '%s\n' "${ROWS[@]}"
    echo
    echo "[1] The native binary exits non-zero (the round trip or the library failed under AOT), so its size is not comparable with the working variants."
    echo
    echo "## Distinct warnings per variant"
    echo
    printf '%s\n' "${DETAILS[@]}"
} >"$OUT/aot-report.md"

echo "Report: $OUT/aot-report.md" >&2
