#!/usr/bin/env python3
"""Generates the startup class libraries for the endpoints benchmarks.

One library per (variant, N): Plain, Cse, Carter and Fe for N in 10, 100 and 500.
Endpoint i of every variant maps GET /items{i}/{id:int} and returns ItemResponse(id, "item{i}").
Run from anywhere: python3 benchmarks/CSharpEssentials.Endpoints.Benchmarks/generate-endpoints.py
"""
from pathlib import Path

SIZES = (10, 100, 500)
ROOT = Path(__file__).resolve().parent.parent / "CSharpEssentials.Endpoints.Benchmarks.Startup"
PREFIX = "CSharpEssentials.Endpoints.Benchmarks.Startup"
ALL_TFMS = "net8.0;net9.0;net10.0;net11.0"
NOWARN = "$(NoWarn);CA1822;CA1050;CA1812;S101;S3903;S1118;CA1515;S2068;IDE0008;IDE0021;IDE0005;IDE0078"
REPO = "..\\..\\..\\"

HEADER = """// <auto-generated/>
// Generated by benchmarks/CSharpEssentials.Endpoints.Benchmarks/generate-endpoints.py. Do not edit.
#nullable enable
"""

USINGS = """using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Routing;
"""

ITEM_RESPONSE = "public sealed record ItemResponse(int Id, string Name);\n"


def ok(i: int) -> str:
    return f'(int id) => global::Microsoft.AspNetCore.Http.Results.Ok(new ItemResponse(id, "item{i}"))'


def route(i: int) -> str:
    return f'"/items{i}/{{id:int}}"'


def plain(n: int) -> str:
    lines = [f"        app.MapGet({route(i)}, {ok(i)});" for i in range(n)]
    return (USINGS + f"\nnamespace {PREFIX}.Plain{n};\n\n" + ITEM_RESPONSE
            + "\npublic static class PlainEndpoints\n{\n"
            + "    public static void Map(IEndpointRouteBuilder app)\n    {\n"
            + "\n".join(lines) + "\n    }\n}\n")


def cse(n: int) -> str:
    types = [
        f"public sealed class Item{i}Endpoint : global::CSharpEssentials.Endpoints.IEndpoint\n{{\n"
        f"    public static void Map(IEndpointRouteBuilder app) => app.MapGet({route(i)}, {ok(i)});\n}}\n"
        for i in range(n)
    ]
    return (USINGS + f'\n[assembly: global::CSharpEssentials.Endpoints.EndpointRegistryName("Cse{n}")]\n'
            + f"\nnamespace {PREFIX}.Cse{n};\n\n" + ITEM_RESPONSE + "\n" + "\n".join(types))


def carter(n: int) -> str:
    types = [
        f"public sealed class Item{i}Module : global::Carter.ICarterModule\n{{\n"
        f"    public void AddRoutes(IEndpointRouteBuilder app) => app.MapGet({route(i)}, {ok(i)});\n}}\n"
        for i in range(n)
    ]
    return (USINGS + "\n// https://github.com/CarterCommunity/Carter/blob/10.0.0/README.md (ICarterModule.AddRoutes, one module per endpoint)\n"
            + f"namespace {PREFIX}.Carter{n};\n\n" + ITEM_RESPONSE + "\n" + "\n".join(types))


def fe(n: int) -> str:
    types = [
        f"public sealed class GetItem{i} : global::FastEndpoints.Endpoint<GetItemRequest, ItemResponse>\n{{\n"
        f"    public override void Configure()\n    {{\n        Get({route(i)});\n        AllowAnonymous();\n    }}\n\n"
        f"    public override global::System.Threading.Tasks.Task HandleAsync(GetItemRequest req, global::System.Threading.CancellationToken ct) =>\n"
        f'        Send.OkAsync(new ItemResponse(req.Id, "item{i}"), ct);\n}}\n'
        for i in range(n)
    ]
    return ("\n// https://fast-endpoints.com/docs/get-started and https://fast-endpoints.com/docs/model-binding (route values bound onto the request DTO)\n"
            + f"namespace {PREFIX}.Fe{n};\n\n" + ITEM_RESPONSE
            + "\npublic sealed class GetItemRequest\n{\n    public int Id { get; set; }\n}\n\n" + "\n".join(types))


def csproj(tfms: str, refs: str, imports: str = "") -> str:
    return f"""<!-- <auto-generated/> Generated by benchmarks/CSharpEssentials.Endpoints.Benchmarks/generate-endpoints.py. Do not edit. -->
<Project Sdk="Microsoft.NET.Sdk">
{imports}
  <PropertyGroup>
    <TargetFrameworks>{tfms}</TargetFrameworks>
    <IsPackable>false</IsPackable>
    <NoWarn>{NOWARN}</NoWarn>
  </PropertyGroup>

  <ItemGroup>
    <FrameworkReference Include="Microsoft.AspNetCore.App" />
  </ItemGroup>

  <ItemGroup>
{refs}
  </ItemGroup>

</Project>
"""


CSE_IMPORT = f'\n  <Import Project="{REPO}CSharpEssentials.Endpoints\\build\\CSharpEssentials.Endpoints.props" />\n'
CSE_REFS = (f'    <ProjectReference Include="{REPO}CSharpEssentials.Endpoints\\CSharpEssentials.Endpoints.csproj" />\n'
            f'    <ProjectReference Include="{REPO}CSharpEssentials.Endpoints.Generators\\CSharpEssentials.Endpoints.Generators.csproj"\n'
            '                      OutputItemType="Analyzer"\n'
            '                      ReferenceOutputAssembly="false" />')
CARTER_REFS = '    <PackageReference Include="Carter" />'
FE_REFS = ('    <PackageReference Include="FastEndpoints" />\n'
           '    <PackageReference Include="FastEndpoints.Generator" PrivateAssets="all"\n'
           '                      IncludeAssets="runtime; build; native; contentfiles; analyzers; buildtransitive" />')

VARIANTS = {
    "Plain": (plain, lambda: csproj(ALL_TFMS, "")),
    "Cse": (cse, lambda: csproj(ALL_TFMS, CSE_REFS, CSE_IMPORT)),
    "Carter": (carter, lambda: csproj("net10.0;net11.0", CARTER_REFS)),
    "Fe": (fe, lambda: csproj(ALL_TFMS, FE_REFS)),
}


def main() -> None:
    for name, (source, project) in VARIANTS.items():
        for n in SIZES:
            folder = ROOT / f"{name}{n}"
            folder.mkdir(parents=True, exist_ok=True)
            (folder / f"{PREFIX}.{name}{n}.csproj").write_text(project().replace("  <ItemGroup>\n\n  </ItemGroup>\n\n", ""), newline="\n")
            (folder / "Endpoints.g.cs").write_text(HEADER + source(n), newline="\n")
            print(f"wrote {folder.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
