#!/usr/bin/env python3
"""Generates the service libraries for the dependency injection benchmarks.

For N in 50 and 500: S{N} holds IService{i}/Service{i} (i < N), each [RegisterScoped], where every service whose index
is a positive multiple of 5 takes IService{i-1} as a constructor dependency, plus ManualS{N}.Register (hand-written
AddScoped calls) and CatalogS{N}.Values (resolves every service). S{N}.Decorators holds Service{i}Decorator for
i < 10, each [Decorates(typeof(IService{i}))], plus ManualDecorationS{N}.Apply (descriptor replacement by hand).
Every variant consumes the same S{N} assembly.
Run from anywhere: python3 benchmarks/CSharpEssentials.DependencyInjection.Benchmarks/generate-services.py
"""
from pathlib import Path

SIZES = (50, 500)
DECORATED = 10
DECORATOR_OFFSET = 1000
ROOT = Path(__file__).resolve().parent.parent / "CSharpEssentials.DependencyInjection.Benchmarks.Services"
PREFIX = "CSharpEssentials.DependencyInjection.Benchmarks.Services"
ALL_TFMS = "net8.0;net9.0;net10.0;net11.0"
NOWARN = "$(NoWarn);CA1822;CA1050;CA1812;S101;S3903;S1118;CA1515;S2068;IDE0008;IDE0021;IDE0005;IDE0078"
REPO = "..\\..\\..\\"
DI = "global::Microsoft.Extensions.DependencyInjection"

HEADER = """// <auto-generated/>
// Generated by benchmarks/CSharpEssentials.DependencyInjection.Benchmarks/generate-services.py. Do not edit.
#nullable enable
"""


def has_dependency(i: int) -> bool:
    return i > 0 and i % 5 == 0


def service(i: int) -> str:
    if has_dependency(i):
        return (f"[global::CSharpEssentials.DependencyInjection.RegisterScoped]\n"
                f"public sealed class Service{i}(IService{i - 1} previous) : IService{i}\n{{\n"
                f"    public IService{i - 1} Previous {{ get; }} = previous;\n\n"
                f"    public int Value() => {i};\n}}\n")
    return (f"[global::CSharpEssentials.DependencyInjection.RegisterScoped]\n"
            f"public sealed class Service{i} : IService{i}\n{{\n    public int Value() => {i};\n}}\n")


def new_service(i: int) -> str:
    if has_dependency(i):
        return f"new Service{i}({DI}.ServiceProviderServiceExtensions.GetRequiredService<IService{i - 1}>(sp))"
    return f"new Service{i}()"


def services(n: int) -> str:
    interfaces = [f"public interface IService{i}\n{{\n    int Value();\n}}\n" for i in range(n)]
    impls = [service(i) for i in range(n)]
    manual = [f"        {DI}.ServiceCollectionServiceExtensions.AddScoped<IService{i}, Service{i}>(services);" for i in range(n)]
    values = [f"        {DI}.ServiceProviderServiceExtensions.GetRequiredService<IService{i}>(sp).Value()," for i in range(n)]
    return (f'\n[assembly: global::CSharpEssentials.DependencyInjection.ServiceRegistryName("S{n}")]\n'
            + f"\nnamespace {PREFIX}.S{n};\n\n" + "\n".join(interfaces) + "\n" + "\n".join(impls)
            + "\n// https://learn.microsoft.com/dotnet/core/extensions/dependency-injection/service-registration\n"
            + f"public static class ManualS{n}\n{{\n"
            + f"    public static void Register({DI}.IServiceCollection services)\n    {{\n"
            + "\n".join(manual) + "\n    }\n}\n"
            + f"\npublic static class CatalogS{n}\n{{\n"
            + "    public static int[] Values(global::System.IServiceProvider sp) =>\n    [\n"
            + "\n".join(values) + "\n    ];\n}\n")


def decorators(n: int) -> str:
    types = [
        f"[global::CSharpEssentials.DependencyInjection.Decorates(typeof(IService{i}))]\n"
        f"public sealed class Service{i}Decorator(IService{i} inner) : IService{i}\n{{\n"
        f"    public int Value() => inner.Value() + {DECORATOR_OFFSET};\n}}\n"
        for i in range(DECORATED)
    ]
    manual = [
        f"        {DI}.Extensions.ServiceCollectionDescriptorExtensions.Replace(services, "
        f"{DI}.ServiceDescriptor.Scoped<IService{i}>(sp => new Service{i}Decorator({new_service(i)})));"
        for i in range(DECORATED)
    ]
    return (f'\n[assembly: global::CSharpEssentials.DependencyInjection.ServiceRegistryName("S{n}Decorators")]\n'
            + f"\nnamespace {PREFIX}.S{n};\n\n" + "\n".join(types)
            + "\n// https://learn.microsoft.com/dotnet/api/microsoft.extensions.dependencyinjection.extensions.servicecollectiondescriptorextensions.replace\n"
            + f"public static class ManualDecorationS{n}\n{{\n"
            + f"    public static void Apply({DI}.IServiceCollection services)\n    {{\n"
            + "\n".join(manual) + "\n    }\n}\n")


def csproj(extra_refs: str = "") -> str:
    return f"""<!-- <auto-generated/> Generated by benchmarks/CSharpEssentials.DependencyInjection.Benchmarks/generate-services.py. Do not edit. -->
<Project Sdk="Microsoft.NET.Sdk">

  <Import Project="{REPO}CSharpEssentials.DependencyInjection\\build\\CSharpEssentials.DependencyInjection.props" />

  <PropertyGroup>
    <TargetFrameworks>{ALL_TFMS}</TargetFrameworks>
    <IsPackable>false</IsPackable>
    <NoWarn>{NOWARN}</NoWarn>
  </PropertyGroup>

  <ItemGroup>
    <ProjectReference Include="{REPO}CSharpEssentials.DependencyInjection\\CSharpEssentials.DependencyInjection.csproj" />
    <ProjectReference Include="{REPO}CSharpEssentials.DependencyInjection.Generators\\CSharpEssentials.DependencyInjection.Generators.csproj"
                      OutputItemType="Analyzer"
                      ReferenceOutputAssembly="false" />{extra_refs}
  </ItemGroup>

</Project>
"""


def write(name: str, project: str, source: str) -> None:
    folder = ROOT / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{PREFIX}.{name}.csproj").write_text(project, newline="\n")
    (folder / "Services.g.cs").write_text(HEADER + source, newline="\n")
    print(f"wrote {folder.relative_to(ROOT.parent)}")


def main() -> None:
    for n in SIZES:
        write(f"S{n}", csproj(), services(n))
        ref = f'\n    <ProjectReference Include="..\\S{n}\\{PREFIX}.S{n}.csproj" />'
        write(f"S{n}.Decorators", csproj(ref), decorators(n))


if __name__ == "__main__":
    main()
