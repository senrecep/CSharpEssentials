using System.Text;

namespace CSharpEssentials.Json.Generators;

/// <summary>
/// Writes the per-assembly registry and the <c>ModuleInitializerAttribute</c> polyfill.
/// </summary>
internal static class PolymorphismSourceWriter
{
    public const string RegistryFileName = "CSharpEssentialsJsonPolymorphism.g.cs";

    private const string Json = "global::CSharpEssentials.Json";

    private static readonly string GeneratedCode =
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"CSharpEssentials.Json.Generators\", \"{typeof(PolymorphismSourceWriter).Assembly.GetName().Version}\")]";

    public static IEnumerable<string> DerivedTypeEntries(DerivedTypeModel model) =>
        model.BaseTypes.Select(baseType =>
            Json + ".PolymorphicRegistration.DerivedType(typeof(" + baseType + "), typeof(" + model.DerivedType + "), " + model.Value + "),");

    public static string PropertyEntry(PropertyModel model) =>
        Json + ".PolymorphicRegistration.Property(typeof(" + model.DeclaringType + "), \"" + model.MemberName + "\", static () => new " +
        Json + ".PolymorphicPropertyConverter<" + model.PropertyType + ">(typeof(" + model.BaseType + "), " + model.PropertyName + ")),";

    public static string WriteRegistry(RegistrySettings settings, EquatableArray<string> entries)
    {
        string registry = "global::" + RegistryNames.Namespace + "." + settings.ClassName;
        StringBuilder w = new();
        w.AppendLine("// <auto-generated/>");
        w.AppendLine("#nullable enable");
        w.AppendLine();
        w.AppendLine("[assembly: " + Json + ".JsonPolymorphismModule(typeof(" + registry + "))]");
        w.AppendLine();
        w.AppendLine("namespace " + RegistryNames.Namespace);
        w.AppendLine("{");
        w.AppendLine("    /// <summary>Registers the polymorphic types of this assembly and of the assemblies it references.</summary>");
        w.AppendLine("    " + GeneratedCode);
        w.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        w.AppendLine("    public static class " + settings.ClassName);
        w.AppendLine("    {");
        w.AppendLine("        private static int s_registered;");
        w.AppendLine();
        w.AppendLine("        /// <summary>Registers the entries once; later calls return at once.</summary>");
        w.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        w.AppendLine("        public static void Register()");
        w.AppendLine("        {");
        w.AppendLine("            if (global::System.Threading.Interlocked.Exchange(ref s_registered, 1) != 0)");
        w.AppendLine("            {");
        w.AppendLine("                return;");
        w.AppendLine("            }");
        w.AppendLine();
        foreach (string referenced in settings.ReferencedRegistries)
        {
            w.AppendLine("            " + referenced + ".Register();");
        }

        w.AppendLine("            " + Json + ".JsonPolymorphism.Register(new " + Json + ".PolymorphicRegistration[]");
        w.AppendLine("            {");
        foreach (string entry in entries)
        {
            w.AppendLine("                " + entry);
        }

        w.AppendLine("            });");
        w.AppendLine("        }");
        w.AppendLine("    }");
        w.AppendLine("}");
        return w.ToString();
    }

    public static string WriteModuleInitializerPolyfill()
    {
        StringBuilder w = new();
        w.AppendLine("// <auto-generated/>");
        w.AppendLine();
        w.AppendLine("namespace System.Runtime.CompilerServices");
        w.AppendLine("{");
        w.AppendLine("    internal sealed partial class ModuleInitializerAttribute : global::System.Attribute");
        w.AppendLine("    {");
        w.AppendLine("    }");
        w.AppendLine("}");
        return w.ToString();
    }
}
