using System.Diagnostics.CodeAnalysis;
using System.Globalization;
using CSharpEssentials.EntityFrameworkCore;
using CSharpEssentials.Enums;
using FluentAssertions;
using Microsoft.Data.Sqlite;

namespace CSharpEssentials.Tests.EntityFrameworkCore.EnumColumns;

public sealed class EnumDataAuditTests : IDisposable
{
    private const string Sqlite = "Microsoft.EntityFrameworkCore.Sqlite";

    private readonly SqliteConnection _connection = new("Data Source=:memory:");

    public EnumDataAuditTests() => _connection.Open();

    public void Dispose() => _connection.Dispose();

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("   ")]
    public void Sql_Should_Throw_When_TableIsBlank(string? table)
    {
        Action act = () => EnumDataAudit.Sql<StoredOrderStatus>(table!, "Status");

        act.Should().Throw<ArgumentException>().WithParameterName(nameof(table));
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("   ")]
    public void Sql_Should_Throw_When_ColumnIsBlank(string? column)
    {
        Action act = () => EnumDataAudit.Sql<StoredOrderStatus>("Orders", column!);

        act.Should().Throw<ArgumentException>().WithParameterName(nameof(column));
    }

    [Fact]
    public void Sql_Should_ListUndefinedNumbersWithCounts_When_ColumnStoresIntegers()
    {
        Run("CREATE TABLE \"Orders\" (\"Id\" INTEGER PRIMARY KEY, \"Status\" INTEGER NULL)");
        Run("INSERT INTO \"Orders\" (\"Status\") VALUES (0), (1), (2), (7), (7), (-1), (NULL)");

        string sql = EnumDataAudit.Sql<StoredOrderStatus>("Orders", "Status", storedAs: EnumStoredAs.Integer, provider: Sqlite);

        Rows(sql).Should().Equal(("-1", 1L), ("7", 2L));
    }

    [Fact]
    public void Sql_Should_ListUndefinedBits_When_FlagsColumnStoresIntegers()
    {
        Run("CREATE TABLE \"Grants\" (\"Id\" INTEGER PRIMARY KEY, \"Access\" INTEGER NULL)");
        Run("INSERT INTO \"Grants\" (\"Access\") VALUES (0), (3), (7), (8), (9), (NULL)");

        string sql = EnumDataAudit.Sql<StoredPermissions>("Grants", "Access", storedAs: EnumStoredAs.Integer, provider: Sqlite);

        Rows(sql).Should().Equal(("8", 1L), ("9", 1L));
    }

    [Fact]
    public void Sql_Should_ListUnknownText_When_ColumnStoresNames()
    {
        Run("CREATE TABLE \"Orders\" (\"Id\" INTEGER PRIMARY KEY, \"Status\" TEXT NULL)");
        Run("INSERT INTO \"Orders\" (\"Status\") VALUES ('Pending'), ('Lost'), ('Lost'), (NULL)");

        string sql = EnumDataAudit.Sql<StoredOrderStatus>("Orders", "Status", provider: Sqlite);

        Rows(sql).Should().Equal(("Lost", 2L));
    }

    [Fact]
    public void Sql_Should_TargetPostgresSchema_When_ProviderIsOmitted()
    {
        string sql = EnumDataAudit.Sql<StoredOrderStatus>("Orders", "Status", schema: "sales", storedAs: EnumStoredAs.Integer);

        sql.Should().StartWith("SELECT \"Status\" AS \"Value\", count(*) AS \"Count\" FROM \"sales\".\"Orders\" WHERE ");
        sql.Should().EndWith("GROUP BY \"Status\" ORDER BY \"Status\";");
    }

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "Test-only helper; the SQL is built from test constants.")]
    private void Run(string sql)
    {
        using SqliteCommand command = _connection.CreateCommand();
        command.CommandText = sql;
        command.ExecuteNonQuery();
    }

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "Test-only helper; the SQL is generated by EnumDataAudit from test constants.")]
    private List<(string Value, long Count)> Rows(string sql)
    {
        using SqliteCommand command = _connection.CreateCommand();
        command.CommandText = sql;
        using SqliteDataReader reader = command.ExecuteReader();
        List<(string, long)> rows = [];
        while (reader.Read())
            rows.Add((Convert.ToString(reader.GetValue(0), CultureInfo.InvariantCulture)!, reader.GetInt64(1)));
        return rows;
    }
}
